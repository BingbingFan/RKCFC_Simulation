# REAL-DATA TABLES for the manuscript, generated from the Study F result files.
#
#   Rscript R/make_realdata_tables.R [results_real_dir] [out_dir]
#
# Defaults: results_real/ and tables/.
#
# WHAT THIS PRODUCES
#   tables/tab06.tex   both methods on both scales (from F1.rds and its starts)
#   tables/tab07.tex   Cox models M1--M5 on the primary partition (from F3.rds)
#   tables/tabS11.tex  baseline characteristics by vital status, analyzed cohort
#   tables/tabS12.tex  baseline characteristics by class of the primary partition
#
# WHY IT EXISTS. The manuscript's Tables 6 and 7 were typed from the run logs on
# 2026-09-10 as an interim, which is exactly the practice the simulation tables
# were built to replace: a number typed once drifts from the evidence the first
# time a block is re-run. These fragments are read from the .rds files, so a
# re-run of F1-F3 updates the manuscript rather than leaving it to be re-typed.
#
# NO IDENTIFIERS. The cohort's baseline table is read through load_cea36(),
# which returns only the analysis set and asserts that no non-ASCII column name
# (the direct identifiers in the raw table) is present. Everything emitted here
# is an aggregate.
#
# The fragments carry no preamble, like the simulation ones, and use the same
# emit() layout so the two families typeset alike.

source(file.path("R", "realdata_load.R"))

args <- commandArgs(trailingOnly = TRUE)
args <- args[args != "--args"]
RES  <- if (length(args) >= 1) args[1] else "results_real"
OUT  <- if (length(args) >= 2) args[2] else "tables"
dir.create(OUT, recursive = TRUE, showWarnings = FALSE)

rd <- function(stage) {
  f <- file.path(RES, stage, paste0(stage, ".rds"))
  if (!file.exists(f)) { message("  (no ", f, ")"); return(NULL) }
  readRDS(f)
}
f1 <- rd("F1"); f2 <- rd("F2"); f3 <- rd("F3")
if (is.null(f1)) stop("F1.rds is required.", call. = FALSE)
if (isTRUE(any(f1$table$smoke))) stop("F1.rds is a smoke run; refusing.", call. = FALSE)

prim <- if (!is.null(f1$primary)) f1$primary else if (exists("REAL_PRIMARY")) REAL_PRIMARY else "raw_M1"
Tmax <- if (!is.null(f1$Tmax)) f1$Tmax else REAL_TMAX
# Class names of the primary partition, label 1 then label 2. The 36-month record
# carries its own (R/realdata36_select.R); the 18-month one has none and keeps the
# names it was published with. Cox models code the class as factor(g), so every
# hazard ratio below is class 2 against class 1.
cn <- if (!is.null(f1$class_names)) f1$class_names else c("rebounding", "flat")

f <- function(x, d = 3) ifelse(is.finite(x), formatC(x, format = "f", digits = d), "---")
# Columns added to F1's table by the multi-start version (n_failed_starts,
# prop_best) are absent from an F1.rds written by the single-start one; read
# them through this so an older file prints "---" instead of dying on NULL[1].
col1 <- function(df, name) if (name %in% names(df) && nrow(df)) df[[name]][1] else NA
esc <- function(x) gsub("_", "\\\\_", gsub("%", "\\\\%", gsub("&", "\\\\&", x)))
pfmt <- function(p) ifelse(!is.finite(p), "---", ifelse(p < 0.001, "$<$0.001", formatC(p, format = "f", digits = 3)))

# Caption split rules (table name in the caption, everything else in the note).
source(file.path("R", "table_captions.R"))

emit <- function(id, caption, label, header, align, rows, notes = NULL,
                 small = TRUE, midrules = integer(0), wide = FALSE) {
  con <- file(file.path(OUT, paste0(id, ".tex")), open = "wt", encoding = "UTF-8")
  on.exit(close(con))
  # Caption = table name only; the rest of the caption opens the note (R/table_captions.R).
  sp <- split_caption(id, caption, notes)
  caption <- sp$caption
  notes <- if (nzchar(sp$notes)) sp$notes else NULL
  w <- function(...) cat(..., "\n", sep = "", file = con)
  w("% ", id, " -- generated by R/make_realdata_tables.R on ", format(Sys.Date()), ". Do not edit by hand.")
  w("\\begin{table}[htbp]")
  w("\\centering")
  if (wide) w("\\setlength{\\tabcolsep}{3pt}\\footnotesize") else if (small) w("\\small")
  w("\\caption{", caption, "}")
  w("\\label{", label, "}")
  w("\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}}", align, "@{}}")
  w("\\toprule")
  w(header, " \\\\")
  w("\\midrule")
  for (i in seq_along(rows)) { w(rows[i], " \\\\"); if (i %in% midrules) w("\\midrule") }
  w("\\bottomrule")
  w("\\end{tabular*}")
  if (!is.null(notes)) { w("\\begin{minipage}{\\linewidth}\\vspace{2pt}\\footnotesize"); w(notes); w("\\end{minipage}") }
  w("\\end{table}")
  message("  wrote ", id, ".tex")
}

# --- Table 6: both methods on both scales ---------------------------------------
# EACH SCALE AT ITS OWN BANDWIDTH (2026-10-03). The bandwidth of the Kendall surface is
# chosen per scale as the smallest at which the iteration converges and starts agree:
# 24 months on the original scale, 10 on the log scale. So when the primary is the
# original-scale run, the log-scale rows come from the log-scale run (its selected
# record, results_real36_sel, or the third argument), not from the log fits that the
# original-scale run also produced at 24 months.
LOGRES <- if (length(args) >= 3) args[3] else if (grepl("^raw", prim) && file.exists("results_real36_sel/F1/F1.rds")) "results_real36_sel" else NA_character_
f1_log <- if (!is.na(LOGRES)) readRDS(file.path(LOGRES, "F1", "F1.rds")) else NULL
if (!is.null(f1_log) && isTRUE(any(f1_log$table$smoke))) stop("the log-scale F1.rds is a smoke run; refusing.", call. = FALSE)
src_of <- function(sc) if (sc == "log" && !is.null(f1_log)) f1_log else f1
{
  rows <- character(0)
  for (sc in c("raw", "log")) for (m in c("M1", "M2")) {
    f1s <- src_of(sc)
    tb  <- f1s$table
    own <- tb[tb$metric_scale == tb$scale, , drop = FALSE]
    bt  <- tb[grepl("back", tb$metric_scale), , drop = FALSE]
    r <- own[own$scale == sc & own$method == m, , drop = FALSE]; if (!nrow(r)) next
    b <- bt[bt$scale == sc & bt$method == m, , drop = FALSE]
    st <- f1s$starts[[paste0(sc, "_", m)]]
    a_med <- if (!is.null(st)) stats::median(st$aRI_to_best[is.finite(st$aRI_to_best)]) else NA_real_
    Jv    <- if (!is.null(st)) st$J[is.finite(st$J)] else numeric(0)
    jsp   <- if (length(Jv) > 1) 100 * (max(Jv) - min(Jv)) / min(Jv) else NA_real_
    rows <- c(rows, paste(
      if (sc == "raw") "original" else "log",
      if (m == "M1") "RKCFC" else "KCFC",
      if (is.na(r$n1[1])) "---" else sprintf("%d / %d", r$n1[1], r$n2[1]),
      if (is.na(r$stop_reason[1])) "failed" else esc(r$stop_reason[1]),
      f(r$rre_in[1]), f(r$rre_out[1]),
      if (nrow(b)) f(b$rre_in[1]) else "---",
      { nf <- col1(r, "n_failed_starts"); if (is.na(nf)) "---" else as.character(nf) },
      if (is.finite(a_med) && a_med >= 0.95) sprintf("\\textbf{%s}", f(a_med)) else f(a_med),
      if (is.finite(jsp)) sprintf("%.1f\\%%", jsp) else "---",
      sep = " & "))
  }
  nst <- if (!is.null(f1$nstart)) f1$nstart else NA
  # The 36-month primary RKCFC partition is the smallest objective over 120 starts
  # (R/realdata36_select.R), not over this fit's 20; say so in the note. The primary
  # scale is the record's (original scale since 2026-10-03; log scale before).
  prim_scale <- sub("_.*$", "", prim)
  prim_scale_txt <- if (prim_scale == "raw") "original" else "log"
  sel_sentence <- function(f1x, scale_txt) {
    if (is.null(f1x$selection)) return("")
    nx <- if (!is.null(f1x$nstart)) f1x$nstart else NA
    sprintf(" For RKCFC on the %s scale the retained partition is the smallest objective over %d starts, these %s and %d more from the stability analysis; %d of the %d reached it.",
            scale_txt, f1x$selection$n_starts, if (is.na(nx)) "" else as.character(nx),
            f1x$selection$n_starts - if (is.na(nx)) 0L else as.integer(nx),
            f1x$selection$n_reached, f1x$selection$n_starts)
  }
  sel_note <- paste0(sel_sentence(f1, prim_scale_txt),
                     if (!is.null(f1_log)) sel_sentence(f1_log, "log") else "")
  realfits_note <- if (Tmax == 18)
    "The RKCFC partition on the log scale is the primary analysis, since it is the only one of the four that repeated starts reproduce, and it separates the classes by shape. Held-out errors above 1 on the original scale arise because a held-out CEA value in the hundreds cannot be predicted from a patient's remaining measurements." else if (prim_scale == "raw")
    sprintf("The RKCFC partition on the original scale is the primary analysis; the log-scale fits are the sensitivity analysis for the scale. The Kendall-surface bandwidth was chosen per scale as the smallest at which the iteration converges and starts agree, %s months on the original scale%s. A held-out error above 1 means that the fit predicts the withheld measurements less well than the sample mean; on the original scale a held-out CEA value in the hundreds cannot be predicted from a patient's remaining measurements.",
            format(f1$bwK), if (!is.null(f1_log)) sprintf(" and %s months on the log scale", format(f1_log$bwK)) else "") else
    "The RKCFC partition on the log scale is the primary analysis, since it is the only one of the four that repeated starts reproduce. A held-out error above 1 means that the fit predicts the withheld measurements less well than the sample mean."
  emit("tab06",
       sprintf("Both methods on both scales, CEA cohort ($n = %d$, 0--%d months, $K = %d$, %s random starts per fit, the smallest objective retained). Relative reconstruction errors are on the scale of the fit; \\emph{back-tr.} is the log-scale fit's in-sample error after back-transformation to the original scale. \\emph{aRI to best} is the median adjusted Rand index between the retained partition and the other starts; \\emph{$J$ spread} is the range of the starts' objectives relative to the smallest.",
               f1$descriptives$n_subjects, as.integer(Tmax), f1$K, if (is.na(nst)) "several" else as.character(nst)),
       "tab:realfits",
       "Scale & Method & Sizes & Stopped & RRE in & RRE held-out & Back-tr. & Starts failed & aRI to best & $J$ spread",
       "llrlcccccc", rows, wide = TRUE,
       notes = paste0(realfits_note, sel_note))
}

# --- Table 7: Cox models on the primary partition -------------------------------
# Since 2026-10-03 F3.rds carries both time origins (column `origin`; `f3$origin` is
# the reported one, from surgery, the month-36 landmark the
# sensitivity analysis). An older F3.rds has one origin, the landmark.
scale_txt <- if (grepl("^raw", prim)) "RKCFC on CEA on its original scale" else "RKCFC on log-transformed CEA"
if (!is.null(f3)) {
  tb <- f3$table
  if (is.null(tb$origin)) tb$origin <- "landmark"
  rep_origin <- if (!is.null(f3$origin)) f3$origin else "landmark"
  origins <- c(rep_origin, setdiff(unique(tb$origin), rep_origin))
  origin_txt <- function(o) if (o == "surgery") "time from surgery, all patients" else sprintf("time from the %d-month landmark, patients alive and under follow-up at it", as.integer(f3$landmark))
  cap1 <- function(x) paste0(toupper(substr(x, 1, 1)), substr(x, 2, nchar(x)))
  # Three models only: unadjusted, multivariable, and the
  # multivariable model with the preoperative CEA added as a sensitivity analysis. The
  # age-and-sex and peak-CEA models are still fitted and stored in F3.rds
  # but are not printed. The covariate list goes to the note, not to a column.
  keep <- c("M1", "M3", "M4")
  lab <- c(M1 = "Unadjusted", M3 = "Multivariable", M4 = "Multivariable + preoperative CEA")
  covs <- "age, sex, body mass index, surgical approach, primary site, tumor differentiation, AJCC stage, lymph node yield, mucinous type, lymphovascular invasion, perineural invasion, and adjuvant chemotherapy"
  rows <- character(0)
  for (o in origins) {
    to <- tb[tb$origin == o & tb$model %in% keep, , drop = FALSE]
    to <- to[match(keep, to$model), , drop = FALSE]
    stopifnot(nrow(to) == length(keep), !anyNA(to$model))
    # Short group labels flush left, model names indented; which
    # origin is reported and which is the sensitivity analysis is stated in the note.
    if (length(origins) > 1)
      rows <- c(rows, sprintf("\\multicolumn{5}{@{}l}{\\emph{%s}}",
                              if (o == "surgery") "Time from surgery" else sprintf("Time from the %d-month landmark", as.integer(f3$landmark))))
    rows <- c(rows, vapply(seq_len(nrow(to)), function(i) {
      m <- to$model[i]
      paste(paste0("\\quad ", lab[[m]]),
            to$n[i], to$events[i],
            sprintf("%.2f (%.2f--%.2f)", to$hr[i], to$lo[i], to$hi[i]),
            pfmt(to$p[i]), sep = " & ")
    }, character(1)))
  }
  ph <- f3$ph
  ph_note <- if (!is.null(ph)) {
    g <- grep("^group", rownames(ph)); a <- grep("^Age", rownames(ph)); G <- grep("GLOBAL", rownames(ph))
    sprintf(" Proportional hazards by scaled Schoenfeld residuals (reported origin) gave class term $P = %s$, global $P = %s$%s.",
            pfmt(ph[g[1], "p"]), pfmt(ph[G[1], "p"]),
            if (length(a)) sprintf(", age $P = %s$", pfmt(ph[a[1], "p"])) else "")
  } else ""
  # The group's own LR contribution in M5 is not stored in F3.rds (it is printed
  # by the runner); F2 stores the threshold-comparator version, at the landmark.
  # Quote that one and say which it is, rather than invent the continuous one.
  lr_note <- if (!is.null(f2) && !is.null(f2$lr_chisq))
    sprintf(" With the peak-CEA threshold that best reproduces the classes (%.2f ng/mL) in the unadjusted model from the %d-month landmark, the class term's likelihood-ratio $\\chi^2$ is %.2f on 1 df, $P = %s$.",
            f2$peak_cut, as.integer(f3$landmark), f2$lr_chisq, pfmt(stats::pchisq(f2$lr_chisq, 1, lower.tail = FALSE))) else ""
  emit("tab07",
       sprintf("Hazard of death in the %s class relative to the %s class (%s, %s), Cox proportional hazards models%s. Each row reports the hazard ratio, its interval and its $P$ value from the same fit.",
               cn[2], cn[1], scale_txt, esc(f3$partition),
               if (length(origins) > 1) sprintf(", %s (reported) and %s (sensitivity)", origin_txt(rep_origin), origin_txt(origins[2])) else sprintf(", %s", origin_txt(rep_origin))),
       "tab:cox",
       "Model & $n$ & Events & HR (95\\% CI) & $P$",
       "lcccc", rows,
       notes = paste0("The multivariable model adjusted for ", covs, ". The model adding the preoperative CEA, which is the trajectory's own first measurement and therefore part of the exposure that defined the classes, is a sensitivity analysis; it is reported to show the attenuation from conditioning on it and is not intended as an estimate of the class effect.",
                      ph_note))
}

# --- Tables S11 and S12: baseline characteristics --------------------------------
{
  d <- truncate_cea36(load_cea36(scale = "raw"), Tmax)
  b <- d$base
  b$`Peak CEA over the window, ng/mL` <- peak_cea(d)
  g <- f1$fits[[prim]]
  if (length(g) != nrow(b)) stop("primary partition length does not match the cohort.", call. = FALSE)

  # Rows to summarize, in manuscript order. Only columns present are used.
  # `bin`: a two-level variable reported as ONE row, the count and share of the
  # level named in `yes`. The first version printed every binary variable as a
  # two-row block under its raw codes ("0" / "1"), seen on the rendered page.
  spec <- list(
    list(col = "Age",                     lab = "Age, years",                       kind = "mean"),
    list(col = "Sex",                     lab = "Male, $n$ (\\%)",                  kind = "bin", yes = "Male"),
    list(col = "BMI",                     lab = "BMI, kg/m$^2$",                    kind = "mean"),
    list(col = "Preoperative_CEA",        lab = "Preoperative CEA, ng/mL",          kind = "median"),
    list(col = "Peak CEA over the window, ng/mL", lab = "Peak CEA over the window, ng/mL", kind = "median"),
    list(col = "Surgical_approach",       lab = "Open resection, $n$ (\\%)",        kind = "bin", yes = "Open_resection"),
    list(col = "Primary_site",            lab = "Rectal primary, $n$ (\\%)",        kind = "bin", yes = "Rectum"),
    list(col = "Tumor_differentiation",   lab = "Tumor differentiation, $n$ (\\%)", kind = "cat", levels = c(Well_moderate = "Well or moderate", Poor_undifferentiated = "Poor or undifferentiated", Unknown = "Unknown")),
    list(col = "AJCC_8th_ed_Stage",       lab = "AJCC stage, $n$ (\\%)",            kind = "cat"),
    list(col = "Lymph_node_yield",        lab = "Lymph node yield below 12, $n$ (\\%)", kind = "bin", yes = "Less_than_12"),
    list(col = "Mucinous_colloid_type",   lab = "Mucinous (colloid) type, $n$ (\\%)", kind = "bin", yes = "Yes"),
    list(col = "Lymphovascular_invasion", lab = "Lymphovascular invasion, $n$ (\\%)", kind = "bin", yes = "Yes"),
    list(col = "Perineural_invasion",     lab = "Perineural invasion, $n$ (\\%)",   kind = "bin", yes = "Yes"),
    list(col = "Adjuvant_chemotherapy",   lab = "Adjuvant chemotherapy, $n$ (\\%)", kind = "bin", yes = "Yes"),
    list(col = "Death",                   lab = "Died during follow-up, $n$ (\\%)", kind = "bin", yes = "1"),
    list(col = "Survival_Time",           lab = "Follow-up, months",                kind = "median"))
  spec <- Filter(function(s) s$col %in% names(b), spec)

  cell_num <- function(x, kind) {
    x <- x[is.finite(x)]
    if (!length(x)) return("---")
    if (kind == "mean") sprintf("%.1f (%.1f)", mean(x), stats::sd(x))
    else sprintf("%.1f [%.1f, %.1f]", stats::median(x), stats::quantile(x, .25), stats::quantile(x, .75))
  }
  p_num <- function(x, grp) tryCatch(
    if (length(unique(grp)) == 2) stats::wilcox.test(x ~ grp)$p.value else stats::kruskal.test(x ~ grp)$p.value,
    error = function(e) NA_real_)
  p_cat <- function(x, grp) tryCatch(suppressWarnings(stats::chisq.test(table(x, grp))$p.value),
                                     error = function(e) NA_real_)

  # `drop`: columns to leave out of a particular table -- the stratifier itself,
  # which would otherwise print as 100% against 0%.
  build <- function(grp, grp_labels, drop = character(0)) {
    levs <- names(grp_labels); rows <- character(0)
    for (s in spec) {
      if (s$col %in% drop) next
      x <- b[[s$col]]
      if (s$kind == "bin") {
        yes <- as.character(x) == as.character(s$yes)
        cells <- vapply(levs, function(L) { n <- sum(grp == L); k <- sum(grp == L & yes, na.rm = TRUE)
                                            sprintf("%d (%.1f)", k, 100 * k / n) }, character(1))
        rows <- c(rows, paste(c(s$lab, cells, pfmt(p_cat(yes, grp))), collapse = " & "))
      } else if (s$kind == "cat") {
        x <- as.factor(x)
        rows <- c(rows, paste(c(s$lab, rep("", length(levs)), pfmt(p_cat(x, grp))), collapse = " & "))
        for (lv in levels(x)) {
          cells <- vapply(levs, function(L) { n <- sum(grp == L); k <- sum(grp == L & x == lv, na.rm = TRUE)
                                              sprintf("%d (%.1f)", k, 100 * k / n) }, character(1))
          rows <- c(rows, paste(c(paste0("\\quad ", if (!is.null(s$levels) && lv %in% names(s$levels)) s$levels[[lv]] else esc(as.character(lv))), cells, ""), collapse = " & "))
        }
      } else {
        x <- suppressWarnings(as.numeric(x))
        cells <- vapply(levs, function(L) cell_num(x[grp == L], s$kind), character(1))
        rows <- c(rows, paste(c(s$lab, cells, pfmt(p_num(x, grp))), collapse = " & "))
      }
    }
    rows
  }
  hdr <- function(grp, grp_labels) {
    levs <- names(grp_labels)
    paste(c("", vapply(levs, function(L) sprintf("%s ($n = %d$)", grp_labels[[L]], sum(grp == L)), character(1)), "$P$"),
          collapse = " & ")
  }
  note <- "Mean (SD) or median [IQR] for numeric variables, $n$ (\\%) for categorical ones. $P$ from the Wilcoxon or Kruskal--Wallis test for numeric variables and the $\\chi^2$ test for categorical ones. BMI, body mass index; CEA, carcinoembryonic antigen."

  if ("Death" %in% names(b)) {
    grp <- ifelse(b$Death == 1, "dead", "alive")
    emit("tabS11",
         sprintf("Baseline characteristics of the analyzed cohort ($n = %d$) by vital status at the end of follow-up.", nrow(b)),
         "tab:baseline_vital",
         hdr(grp, c(dead = "Died", alive = "Survived")),
         "lccc", build(grp, c(dead = "Died", alive = "Survived"), drop = "Death"), notes = note)
  }
  grp <- ifelse(g == 1L, "c1", "c2")
  emit("tabS12",
       sprintf("Baseline characteristics of the analyzed cohort by trajectory class (%s, %s). Class 1 is the %s class and class 2 the %s class.", scale_txt, esc(prim), cn[1], cn[2]),
       "tab:baseline_class",
       hdr(grp, c(c1 = sprintf("Class 1 (%s)", cn[1]), c2 = sprintf("Class 2 (%s)", cn[2]))),
       "lccc", build(grp, c(c1 = sprintf("Class 1 (%s)", cn[1]), c2 = sprintf("Class 2 (%s)", cn[2]))), notes = note)
}
message("done: ", OUT, "/")
